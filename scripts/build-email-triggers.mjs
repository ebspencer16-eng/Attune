#!/usr/bin/env node
/**
 * Works out which emails anything actually sends, and writes it down.
 *
 * ── WHY ───────────────────────────────────────────────────────────────────
 * api/send-email.js can build ten emails. Four of them have no trigger
 * anywhere in the codebase: workbook_ready and partner_joined_notification
 * were retired at their triggers in 2793bba, beta_survey went the same way in
 * the same commit, and checkin_1yr is sent by api/cron-checkin.js from its own
 * template rather than through this endpoint. The templates stayed.
 *
 * That matters because /email-preview is where Ellie reads email copy, and she
 * writes every word a customer sees. A page that lists ten emails when four of
 * them cannot be sent is the same failure as the copy-review document that
 * showed ten action items the product never rendered: copy gets reviewed and
 * approved that nobody will ever read, and the ones that ship get less
 * attention for it.
 *
 * So the preview says, next to each email, how many places send it. This file
 * is where that count comes from, and it is generated rather than typed.
 *
 * ── METHOD, WHICH IS THE PART TO ARGUE WITH ───────────────────────────────
 * A trigger is a `type: '<name>'` appearing within 600 characters after a
 * mention of /api/send-email or a call to sendEmailWithRetry. That is narrow
 * on purpose. A bare search for the name finds things that are not sends: the
 * string 'beta_survey' appears in a POST to /api/get-feedback, which is a
 * different endpoint entirely, and counting it would have called that email
 * live.
 *
 * It will miss a type held in a variable. Nothing does that today, and
 * check-email-triggers.mjs fails the build if the generated file stops
 * matching, so the day something does it will be visible.
 */

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = join(ROOT, 'api/_lib/email-triggers.js');
const SENDER = 'api/send-email.js';

/** How far after a send mention a type still counts as part of that call. */
const WINDOW = 600;

function files(dir, out = []) {
  for (const name of readdirSync(join(ROOT, dir))) {
    const rel = join(dir, name);
    if (statSync(join(ROOT, rel)).isDirectory()) {
      if (/node_modules|\.expo|^ios$|^android$|dist/.test(name)) continue;
      files(rel, out);
      continue;
    }
    if (/\.(js|jsx|ts|tsx|html)$/.test(name)) out.push(rel);
  }
  return out;
}

const scanned = ['src', 'public', 'api', 'attune-app/src'].flatMap((d) => files(d));
const triggers = {};

for (const rel of scanned) {
  if (rel === SENDER) continue;                        // the sender is not a trigger
  if (rel.endsWith('email-triggers.js')) continue;     // nor is this file's output
  if (rel === 'public/email-preview.html') continue;   // nor is the preview page
  const src = readFileSync(join(ROOT, rel), 'utf8');
  const lineAt = (i) => src.slice(0, i).split('\n').length;

  for (const m of src.matchAll(/\/api\/send-email|sendEmailWithRetry\s*\(/g)) {
    const window = src.slice(m.index, m.index + WINDOW);
    for (const t of window.matchAll(/type:\s*['"]([a-z0-9_]+)['"]/gi)) {
      const at = m.index + t.index;
      // A line that documents the call is not a call. sendEmailWithRetry's own
      // doc comment says "Usage: sendEmailWithRetry({ type: 'partner_invite'",
      // which counted as a seventh trigger until this skipped it.
      const lineStart = src.lastIndexOf('\n', at) + 1;
      const before = src.slice(lineStart, at);
      if (/^\s*(\/\/|\*|<!--)/.test(before)) continue;
      (triggers[t[1]] ||= []).push(`${rel}:${lineAt(at)}`);
    }
  }
}

for (const k of Object.keys(triggers)) triggers[k] = [...new Set(triggers[k])].sort();

const body = `/**
 * GENERATED by scripts/build-email-triggers.mjs. Do not edit.
 *
 * Where each email type is actually sent from. A type that is missing here is
 * one api/send-email.js can build and nothing asks for. See the generator for
 * what counts as a trigger and what that method misses.
 */

export const EMAIL_TRIGGERS = ${JSON.stringify(triggers, null, 2)};

/** The types something sends. */
export const SENT_TYPES = Object.keys(EMAIL_TRIGGERS).sort();
`;

if (process.argv.includes('--print')) {
  process.stdout.write(body);
} else {
  writeFileSync(OUT, body);
  const n = Object.keys(triggers).length;
  console.log(`[build-email-triggers] ${n} email types have a trigger, from ${scanned.length} files.`);
}
