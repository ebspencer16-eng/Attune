#!/usr/bin/env node
/**
 * Works out which in-app alerts anything actually raises, and writes it down.
 *
 * ── WHY ───────────────────────────────────────────────────────────────────
 * api/_lib/notifications.js can build six alerts. For most of this product's
 * life exactly one of them was ever raised, by api/delete-account.js, and the
 * other five were copy on a shelf: written, reviewed, and unreachable. That is
 * the /email-preview failure in a second place, and the reason it went unseen
 * for so long is that nothing wrote down which kinds had a caller.
 *
 * So this does, generated rather than typed, next to the same record for
 * emails. A kind with an empty list is one the server knows how to say and
 * nothing asks it to.
 *
 * ── TWO WAYS TO BE RAISED, AND THEY ARE NOT THE SAME ──────────────────────
 * `recordNotification` writes a row on somebody's home screen. `pushOnly`
 * sends a push and writes no row, which is right for the two kinds where the
 * home screen already carries a card saying the same sentence: an alert above
 * it would be the same prompt printed twice, and that was Ellie's instruction.
 *
 * So a kind can be raised as a row, as a push, or as both, and a record that
 * knew only about rows reported four of Ellie's six approved pushes as having
 * no caller at all. The lists are kept apart for that reason: "has no row" and
 * "nothing raises it" are different facts and the second one is the bug.
 *
 * ── METHOD, WHICH IS THE PART TO ARGUE WITH ───────────────────────────────
 * A trigger is `kind: '<name>'` within WINDOW characters after a call to
 * recordNotification or pushOnly. Narrow on purpose: the bare string
 * 'new_post' appears in the copy table itself and in the push rate limiter,
 * and counting either would report a kind as raised when nothing raises it.
 *
 * The kinds themselves are read out of notificationFor's switch rather than
 * listed here, so adding a kind adds a row, empty, rather than quietly not
 * appearing at all. That is the whole point: the gap has to be visible.
 *
 * It will miss a kind held in a variable. Nothing does that today, and
 * check-notification-triggers.mjs fails the build when the record stops
 * matching, so the day something does it will be visible.
 */

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = join(ROOT, 'api/_lib/notification-triggers.js');
const SOURCE = 'api/_lib/notifications.js';

/** How far after a recordNotification call a kind still counts as that call. */
const WINDOW = 400;

function files(dir, out = []) {
  for (const name of readdirSync(join(ROOT, dir))) {
    const rel = join(dir, name);
    if (statSync(join(ROOT, rel)).isDirectory()) {
      if (/node_modules|\.expo|^ios$|^android$|dist/.test(name)) continue;
      files(rel, out);
      continue;
    }
    if (/\.(js|jsx|ts|tsx)$/.test(name)) out.push(rel);
  }
  return out;
}

// Every kind the copy table can build, read from its switch.
const copy = readFileSync(join(ROOT, SOURCE), 'utf8');
const kinds = [...copy.matchAll(/case\s+'([a-z0-9_]+)':/g)].map((m) => m[1]);
if (!kinds.length) {
  console.error('[build-notification-triggers] no kinds found in', SOURCE);
  process.exit(1);
}

const triggers = Object.fromEntries(kinds.map((k) => [k, []]));
const pushes = Object.fromEntries(kinds.map((k) => [k, []]));

/** The two ways a kind is raised, and where each one's record goes. */
const RAISERS = [
  { call: /recordNotification\s*\(/g, into: triggers },
  { call: /pushOnly\s*\(/g, into: pushes },
];

for (const rel of ['src', 'public', 'api', 'attune-app/src'].flatMap((d) => files(d))) {
  if (rel === SOURCE) continue;                             // the writer is not a caller
  if (rel.endsWith('notification-triggers.js')) continue;   // nor is this file's output
  const src = readFileSync(join(ROOT, rel), 'utf8');
  const lineAt = (i) => src.slice(0, i).split('\n').length;

  for (const { call, into } of RAISERS) {
    for (const m of src.matchAll(call)) {
      const window = src.slice(m.index, m.index + WINDOW);
      for (const t of window.matchAll(/kind:\s*['"]([a-z0-9_]+)['"]/g)) {
        const at = m.index + t.index;
        // A line that documents the call is not a call.
        const lineStart = src.lastIndexOf('\n', at) + 1;
        if (/^\s*(\/\/|\*|<!--)/.test(src.slice(lineStart, at))) continue;
        if (!into[t[1]]) continue;                          // a kind with no copy
        into[t[1]].push(`${rel}:${lineAt(at)}`);
      }
    }
  }
}

for (const k of Object.keys(triggers)) {
  triggers[k] = [...new Set(triggers[k])].sort();
  pushes[k] = [...new Set(pushes[k])].sort();
}

const body = `/**
 * GENERATED by scripts/build-notification-triggers.mjs. Do not edit.
 *
 * Where each alert kind is actually raised. An empty list is a kind the server
 * has copy for and nothing asks it to say. See the generator for what counts
 * as a trigger and what that method misses.
 */

export const NOTIFICATION_TRIGGERS = ${JSON.stringify(triggers, null, 2)};

/**
 * Where each kind is raised as a PUSH, which writes no row.
 *
 * A kind in here and not in NOTIFICATION_TRIGGERS is deliberate: the home
 * screen already carries a card with that sentence on it, and an alert row
 * above the card would be the same prompt printed twice.
 */
export const PUSH_TRIGGERS = ${JSON.stringify(pushes, null, 2)};

/** The kinds something raises, either way. */
export const RAISED_KINDS = Object.keys(NOTIFICATION_TRIGGERS)
  .filter((kind) => NOTIFICATION_TRIGGERS[kind].length || PUSH_TRIGGERS[kind].length).sort();

/** The kinds with copy and no caller of any kind. */
export const UNRAISED_KINDS = Object.keys(NOTIFICATION_TRIGGERS)
  .filter((kind) => !NOTIFICATION_TRIGGERS[kind].length && !PUSH_TRIGGERS[kind].length).sort();

/** Raised as a push and deliberately not as a row. */
export const PUSH_ONLY_KINDS = Object.keys(PUSH_TRIGGERS)
  .filter((kind) => PUSH_TRIGGERS[kind].length && !NOTIFICATION_TRIGGERS[kind].length).sort();
`;

if (process.argv.includes('--print')) {
  process.stdout.write(body);
} else {
  writeFileSync(OUT, body);
  const rows = Object.values(triggers).filter((v) => v.length).length;
  const pushed = Object.keys(pushes).filter((k) => pushes[k].length).length;
  const raised = kinds.filter((k) => triggers[k].length || pushes[k].length).length;
  console.log(`[build-notification-triggers] ${raised} of ${kinds.length} alert kinds have a caller:`
    + ` ${rows} write a row, ${pushed} send a push.`);
}
