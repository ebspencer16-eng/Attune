// Writes api/_lib/legal-version.js from the published legal documents.
//
// ── WHY A HASH AND NOT A DATE ─────────────────────────────────────────────
// The retention policy promises "Timestamped records of user consent events
// (when each partner accepted Terms and Privacy Policy)". To record that
// honestly you need to say which version they accepted, and a date does not
// answer it: two of the five documents on /legal are published today reading
// "Effective date: TODO before publishing", and an effective date is a legal
// decision rather than something a build should invent.
//
// The content answers it exactly. This hashes the text of the Privacy Policy
// and the Terms of Service, the two documents the policy names, and that hash
// is the version. Change a word in either and every consent recorded from then
// on refers to the new text, automatically and without anyone remembering to
// bump a number.
//
// It does not replace the effective date. When Ellie sets those two dates the
// hash changes with them, which is correct: the document did change.
//
// Run before build, like build-pkg-rules and build-flags. The result is
// committed so the site works from a plain checkout, and check-legal-version
// fails the build when it drifts.

import { createHash } from 'crypto';
import { readFileSync, writeFileSync } from 'fs';

import { docText } from './_lib/legal-docs.mjs';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = `${ROOT}api/_lib/legal-version.js`;

const html = readFileSync(`${ROOT}public/legal.html`, 'utf8');


const DOCS = ['privacy', 'terms'];
const parts = [];
for (const id of DOCS) {
  const text = docText(html, id);
  if (!text || text.length < 500) {
    console.error(`[build-legal-version] could not read the ${id} document from public/legal.html`);
    console.error('  Refusing to write a version for documents it cannot see.');
    process.exit(1);
  }
  parts.push(`${id}:${text}`);
}

const hash = createHash('sha256').update(parts.join('\n')).digest('hex').slice(0, 12);

const file = `/**
 * Which version of the legal documents a person agreed to.
 *
 * GENERATED by scripts/build-legal-version.mjs. Do not edit.
 *
 * It is a hash of the text of the Privacy Policy and the Terms of Service on
 * public/legal.html, which is what makes a consent record mean something: it
 * says exactly which words were on the page, and it changes the moment they
 * do. A date could not do that, and two of those documents are published
 * today with no date at all.
 */
export const LEGAL_VERSION = '${hash}';

/** The documents the version covers, in the order they are hashed. */
export const LEGAL_DOCUMENTS = ${JSON.stringify(DOCS)};
`;

const before = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return ''; } })();
if (before === file) {
  console.log(`[build-legal-version] api/_lib/legal-version.js already at ${hash}.`);
} else {
  writeFileSync(OUT, file);
  console.log(`[build-legal-version] api/_lib/legal-version.js written: ${hash}.`);
}
