#!/usr/bin/env node
/**
 * The alert copy in TASKS.md has to be the copy the app sends.
 *
 * ── THE PROMISE ───────────────────────────────────────────────────────────
 * Ellie reads copy in TASKS.md. If the table there stops matching
 * api/_lib/notifications.js, she reviews and approves words nobody will see,
 * while the words that ship go through no review at all. That has happened
 * twice on this project, on /email-preview and in the copy-review document,
 * and both times the second surface looked right the whole while.
 *
 * So the table is generated and this regenerates it and refuses a difference.
 * Same shape as check-email-triggers.mjs and check-flags.mjs.
 *
 * ── WHAT IT DELIBERATELY DOES NOT COVER ───────────────────────────────────
 * Whether the words are good. That is Ellie's, which is the whole reason the
 * table exists.
 */

import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const ROOT = new URL('..', import.meta.url).pathname;
const START = '<!-- notification-copy: generated by scripts/build-notification-copy-doc.mjs -->';
const END = '<!-- end notification-copy -->';

const doc = readFileSync(`${ROOT}TASKS.md`, 'utf8');
const from = doc.indexOf(START);
const to = doc.indexOf(END);
if (from < 0 || to < 0) {
  console.error('[check-notification-copy-doc] the generated block is gone from TASKS.md.');
  console.error('Run: node scripts/build-notification-copy-doc.mjs');
  process.exit(1);
}
const onDisk = doc.slice(from, to + END.length);
const fresh = execFileSync('node', [`${ROOT}scripts/build-notification-copy-doc.mjs`, '--print'], { encoding: 'utf8' });

if (fresh !== onDisk) {
  console.error('[check-notification-copy-doc] TASKS.md no longer shows the copy the app sends.');
  console.error('Run: node scripts/build-notification-copy-doc.mjs');
  const a = onDisk.split('\n');
  const b = fresh.split('\n');
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] !== b[i]) {
      console.error(`\n  line ${i + 1}`);
      console.error(`    in TASKS.md: ${a[i] ?? '(nothing)'}`);
      console.error(`    in the code: ${b[i] ?? '(nothing)'}`);
      break;
    }
  }
  process.exit(1);
}

const lines = onDisk.split('\n').filter((l) => /^\| (On|\*\*Off\*\*) \|/.test(l)).length;
console.log(`[check-notification-copy-doc] TASKS.md shows all ${lines} alerts exactly as the app sends them.`);
