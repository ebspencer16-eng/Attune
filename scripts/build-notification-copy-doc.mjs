#!/usr/bin/env node
/**
 * Writes the alert copy into TASKS.md, generated from the alerts themselves.
 *
 * ── WHY IT IS GENERATED ───────────────────────────────────────────────────
 * Ellie: "Hard to find the notification language through the code, please
 * build me a list in tasks to check quickly."
 *
 * She is right that reading a switch statement is not a way to review copy.
 * She has also been bitten twice by the fix for that being a second document:
 * /email-preview held six hand-written mock-ups while the product sent
 * nineteen real emails, and the copy-review document listed ten action items
 * the product never rendered. Both were surfaces built to show the product
 * that quietly became a second draft of it.
 *
 * So this list is not typed. It runs notificationFor for every kind, with
 * sample names, and writes what comes back. If a word changes in the code the
 * table changes with it, and check-notification-copy-doc.mjs fails the build
 * if the two have drifted.
 *
 * It also says, per row, whether anything raises that alert. A list that mixes
 * live copy with copy nothing sends spends review attention on the wrong half,
 * which is the same lesson from the same page.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('..', import.meta.url).pathname;
const DOC = `${ROOT}TASKS.md`;
const START = '<!-- notification-copy: generated by scripts/build-notification-copy-doc.mjs -->';
const END = '<!-- end notification-copy -->';

const { notificationFor } = await import(`${ROOT}api/_lib/notifications.js`);
const { NOTIFICATION_TRIGGERS } = await import(`${ROOT}api/_lib/notification-triggers.js`);

/** Every kind with copy, in the order the switch declares them. */
const kinds = [...readFileSync(`${ROOT}api/_lib/notifications.js`, 'utf8')
  .matchAll(/case\s+'([a-z0-9_]+)':/g)].map((m) => m[1]);

/** When each one fires, in words. Mine to write; the copy itself is not. */
const WHEN = {
  partner_finished: 'your partner finishes the last exercise, so your results open',
  results_ready: 'your own results open',
  partner_nudged_you: 'your partner taps Send a reminder',
  partner_shared: 'your partner shares a note with you',
  new_post: 'a new In Practice post is published',
  partner_deleted: 'your partner deletes their account',
};

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');

const rows = kinds.map((kind) => {
  const a = notificationFor(kind, {
    partnerName: 'Preston',
    postTitle: 'the post title',
    dimensionLabel: 'Conflict Patterns',
  });
  const raised = (NOTIFICATION_TRIGGERS[kind] || []).length;
  return `| ${raised ? 'On' : '**Off**'} | ${esc(WHEN[kind] || kind)} | ${esc(a.title)} | ${esc(a.body)} |`;
});

const off = kinds.filter((k) => !(NOTIFICATION_TRIGGERS[k] || []).length);

const block = `${START}

Generated from the alerts themselves, so it cannot drift from what the app
shows. Preston stands in for a partner's first name. ${off.length
  ? `The ${off.length} marked **Off** are written and deliberately not sent, because the home screen already carries a card saying the same thing.`
  : 'Every one of these is sent.'}

| | When it is sent | Title | Line under it |
|--|--|--|--|
${rows.join('\n')}

${END}`;

const doc = readFileSync(DOC, 'utf8');
const from = doc.indexOf(START);
const to = doc.indexOf(END);
if (from < 0 || to < 0) {
  console.error('[build-notification-copy-doc] TASKS.md has no notification-copy block to fill.');
  console.error('Add these two lines where the table belongs:');
  console.error(`  ${START}\n  ${END}`);
  process.exit(1);
}
const out = doc.slice(0, from) + block + doc.slice(to + END.length);

if (process.argv.includes('--print')) {
  process.stdout.write(block);
} else {
  writeFileSync(DOC, out);
  console.log(`[build-notification-copy-doc] ${rows.length} alerts written into TASKS.md, ${off.length} of them off.`);
}
