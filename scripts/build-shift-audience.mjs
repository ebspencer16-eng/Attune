#!/usr/bin/env node
/**
 * Who each piece of shift prose is actually telling to do something.
 *
 * ── WHY ───────────────────────────────────────────────────────────────────
 * Ellie: "For Preston and Me, our internal processing action item is for both
 * of us, the how you connect action item is for me, and the when things get
 * hard action item is for Preston. The action item for Preston should not be
 * included in my list of things to consider, and vice versa."
 *
 * The three Communication rows on What Comes Next are each a domain's shift
 * prose, and that prose is written about the couple: it names both people and
 * then, often, asks one of them to do something. Both partners are served the
 * same sentence, because `getDimShift` names people by POSITION (whoever
 * scored lower is `loName`) rather than by who is reading.
 *
 * So an item's audience is a property of the sentence, not of the reader, and
 * it can be recorded once per entry.
 *
 * ── WHY GENERATED AND NOT TYPED ───────────────────────────────────────────
 * 150 entries. A hand-typed table beside prose is a table that silently stops
 * describing the prose the first time a sentence is edited, which is this
 * codebase's entire failure mode. This reads the prose and writes the table,
 * and check-shift-audience fails the build when the committed table and a
 * fresh run disagree.
 *
 * ── THE RULE, STATED NEXT TO THE NUMBER ───────────────────────────────────
 * An entry is one-sided only when BOTH of these hold:
 *
 *   1. exactly one of the two names is followed by an instruction modal
 *      (can, could, should, commits to, gets to, must), and
 *   2. the sentence carries no joint instruction: no "you both", "both of
 *      you", "each of you", no "agree that", and no clause beginning with a
 *      bare imperative that asks the pair to do something together (agree,
 *      try, make, name, set, practice, put, keep, decide, pick, check, say,
 *      ask, talk, and the rest of the list below).
 *
 * Everything else is `both`, and that is deliberate: a wrong `both` shows an
 * item to somebody who might not have needed it, which is the behaviour the
 * product has had all along. A wrong one-sided answer HIDES an item from
 * somebody, which is a thing they can never discover. When the rule is not
 * sure, it is not allowed to hide anything.
 *
 * Run: node scripts/build-shift-audience.mjs
 * Writes: api/_content/shift-audience.js
 */

import { writeFileSync } from 'node:fs';
import { SHIFTS } from '../api/_content/v1.js';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = `${ROOT}api/_content/shift-audience.js`;

/** Sentinels, so the prose can be read without two real names in it. */
const LO = '«LO»';
const HI = '«HI»';

/**
 * A name followed by something that asks that person to act.
 *
 * "needs to" and "has to" were in this list and both are descriptive far more
 * often than not: "before «LO» has to ask" is a clause about the other
 * person's action, and it was enough to attribute the whole entry to «LO» and
 * hide it from the person it was actually telling to do something. Reviewed
 * against all 150 sentences, which is the only way that showed.
 */
const INSTRUCTS = (who) => new RegExp(
  `${who}\\s+(?:can|could|should|shouldn't|commits\\b|commits to|gets to|must)\\b`,
);

/** A sentence that asks the pair, which makes the whole entry theirs. */
const JOINT = [
  /\byou both\b/i,
  /\bboth of you\b/i,
  /\beach of you\b/i,
  /\bthe two of you\b/i,
  /\bagree (that|on|in advance|to)\b/i,
  /* Case-insensitive on purpose: "The shift: agree that..." puts the joint
     instruction mid-sentence and in lower case, and a capitals-only version of
     this list read one of those as an instruction to one partner. */
  /(^|[.:;]\s)(agree|try|make|name|set|practice|put|keep|decide|pick|check|say|ask|talk|build|start|use|give|leave|add|write|plan)\b/i,
];

export function audienceOf(text) {
  const s = String(text || '');
  if (JOINT.some((re) => re.test(s))) return 'both';
  const lo = INSTRUCTS(LO).test(s);
  const hi = INSTRUCTS(HI).test(s);
  if (lo && !hi) return 'lo';
  if (hi && !lo) return 'hi';
  return 'both';
}

const shifts = SHIFTS(LO, HI);
const table = {};
let one = 0;
let total = 0;
for (const dim of Object.keys(shifts)) {
  const entries = {};
  for (const [key, text] of Object.entries(shifts[dim])) {
    const who = audienceOf(text);
    total += 1;
    if (who !== 'both') one += 1;
    entries[key] = who;
  }
  table[dim] = entries;
}

const body = Object.entries(table).map(([dim, entries]) => {
  const rows = Object.entries(entries).map(([k, v]) => `    '${k}': '${v}',`).join('\n');
  return `  ${dim}: {\n${rows}\n  },`;
}).join('\n');

const out = `/**
 * Who each shift sentence is telling to do something: 'lo', 'hi' or 'both'.
 *
 * GENERATED by scripts/build-shift-audience.mjs from the prose in v1.js. Do
 * not edit: the next run overwrites it, and check-shift-audience fails the
 * build when this file and the prose disagree.
 *
 * 'lo' and 'hi' are positions, not people: 'lo' is whoever scored lower on the
 * dimension, which is what getDimShift calls loName. The viewer is one of the
 * two, so the surface turns this into "mine", "theirs" or "ours".
 *
 * The rule that produced it, and why it refuses to guess, is in the builder's
 * header. ${one} of ${total} entries are one-sided; the rest are both.
 */

export const SHIFT_AUDIENCE = {
${body}
};
`;

if (out.length < 2000) throw new Error(`refusing to write ${out.length} bytes; the table is empty`);
writeFileSync(OUT, out);
console.log(`[build-shift-audience] ${total} entries, ${one} of them addressed to one person.`);
