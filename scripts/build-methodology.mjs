#!/usr/bin/env node
/**
 * METHODOLOGY.md: how every number in Attune is produced.
 *
 * ── THE PROMISE ───────────────────────────────────────────────────────────
 * Ellie: "I want a methodology document that is kept current. Every backend
 * analysis process: weighting, scoring, thresholds, how each number is
 * produced. For me and Carolina, and shareable."
 *
 * ── WHY IT IS GENERATED AND NOT WRITTEN ───────────────────────────────────
 * "Kept current" is the whole requirement, and a hand-written methodology
 * document is the most reliable way to be wrong about a product. CLAUDE.md's
 * own list of failures has two of exactly this shape: the copy-review document
 * that showed ten action items nothing renders, and the email preview page
 * that hand-wrote six mock-ups while the product sent nineteen. Both were
 * surfaces built to describe the product that quietly became a second draft
 * of it.
 *
 * So every weight, every threshold and every list below is read out of the
 * module that the running product reads. If a weight changes, this document
 * changes with it, and check-methodology.mjs fails the build if the committed
 * copy has fallen behind.
 *
 * ── AND WHY IT IS A FILE RATHER THAN A ROW IN TASKS.md ────────────────────
 * CLAUDE.md says to ask that before adding a document. The answer here is that
 * she asked for something shareable with Carolina, who does not read TASKS.md
 * and should not have to.
 *
 * ── WHAT IT DELIBERATELY DOES NOT CONTAIN ─────────────────────────────────
 * The copy. What a dimension's prose SAYS is reviewed in WORDS-REVIEW.md and
 * COUPLE-TYPE-COPY-REVIEW.md, which are her documents and have their own
 * round trip. This is the arithmetic.
 *
 * Run: node scripts/build-methodology.mjs
 * Checked by: check-methodology.mjs, which is in `npm run check`. This
 * generator is NOT, deliberately: a document the build regenerates before
 * checking it is a comparison of a file with itself.
 */

import { writeFileSync } from 'node:fs';

import {
  DIM_KEYS, QUESTION_WEIGHTS, AXIS_CONFIG, FLIPPED_QUESTIONS, PARTNER_VIEW_BLEND,
} from '../api/_type-engine.js';
import { DIM_META } from '../api/_workbook-content.js';
import { ALIGNMENT_BANDS } from '../api/_lib/alignment.js';
import { ALIGNMENT_THRESHOLD } from '../api/_lib/results.js';
import { CARD_ALIGNED_GAP } from '../api/_lib/comm-alignment.js';
import {
  RESPONSIBILITY_CATEGORIES, EXPECTATIONS_CATEGORIES, LIFE_QUESTIONS, PERSONALITY_QUESTIONS,
} from '../api/_questions.js';
import { LIFE_QUESTION_OPTIONS, EXP_DOMAINS } from '../api/_workbook-content.js';
import { INTIMACY_DIMENSIONS, INTIMACY_QUESTIONS } from '../api/_intimacy-questions.js';
import { COMM_DOMAINS } from '../api/_lib/comm-domains.js';
import { FREQUENCY_LABELS, PATTERN_COPY } from '../api/_conflict-results-prose.js';

const OUT = new URL('../METHODOLOGY.md', import.meta.url).pathname;

const label = (dim) => DIM_META[dim]?.label || dim;
const pct = (n) => `${Math.round(n * 100)}%`;

/** A question's text, for a table that names the questions a dimension reads. */
const QUESTION_TEXT = Object.fromEntries(
  PERSONALITY_QUESTIONS.map((q) => [q.id, (q.text || q.topic || '').trim()]),
);

export function build() {
  const L = [];
  const w = (...lines) => L.push(...lines);

  w('# How Attune produces its numbers',
    '',
    '<!-- Generated by scripts/build-methodology.mjs. Do not edit by hand: the next',
    '     run overwrites it. Every figure below is read out of the module the running',
    '     product reads, so this cannot describe a version of the scoring that is no',
    '     longer live. check-methodology.mjs fails the build if the committed copy',
    '     has fallen behind the code. -->',
    '',
    'Every weight, threshold and list in this document is read out of the code that',
    'serves customers. Nothing here is a description of the scoring written beside',
    'it; if a weight changes, this page changes with it or the build fails.',
    '',
    'What it does not cover is the writing. What a result SAYS is reviewed in',
    'WORDS-REVIEW.md and COUPLE-TYPE-COPY-REVIEW.md. This is the arithmetic.',
    '');

  // ── 1. COMMUNICATION ────────────────────────────────────────────────────
  w('## 1. Communication',
    '',
    `Ten dimensions, scored one to five, from ${PERSONALITY_QUESTIONS.length} questions.`,
    'Each person answers about themselves and about their partner. Those are two',
    'different numbers and the product keeps them apart on purpose: see §1.3.',
    '',
    '### 1.1 Which questions make which dimension, and how much each counts',
    '',
    'A dimension is a weighted mean of its questions. The weights are not equal',
    'and they are not a tuning parameter anybody adjusts: they are the question',
    "set's own design.",
    '',
    '| Dimension | Question | Weight | What it asks |',
    '|--|--|--|--|');
  for (const dim of Object.keys(DIM_KEYS)) {
    const weights = QUESTION_WEIGHTS[dim] || {};
    const ids = Object.keys(weights).length ? Object.keys(weights) : DIM_KEYS[dim];
    ids.forEach((id, i) => {
      const text = (QUESTION_TEXT[id] || '').replace(/\|/g, '/').slice(0, 72);
      w(`| ${i === 0 ? `**${label(dim)}**` : ''} | \`${id}\` | ${weights[id] != null ? pct(weights[id]) : 'equal'} | ${text} |`);
    });
  }
  w('',
    `**Reverse-worded questions.** ${[...FLIPPED_QUESTIONS].map((q) => `\`${q}\``).join(', ')}.`,
    'A high answer there means the opposite of a high answer elsewhere in the same',
    'dimension, so the score is flipped before it is averaged. Getting this wrong',
    'inverts a dimension while looking entirely plausible, which is why one module',
    'owns it and two gates run both surfaces over the same answers.',
    '');

  // ── 1.2 axes
  w('### 1.2 From ten dimensions to two axes',
    '',
    'The couple map has two axes. Each is a weighted mean of some of the ten,',
    'and some dimensions are inverted before they are counted, because a high',
    'score on them points the other way along that axis.',
    '',
    '| Axis | Dimension | Weight | Inverted |',
    '|--|--|--|--|');
  for (const axis of ['withdraw', 'open']) {
    const rows = Object.entries(AXIS_CONFIG).filter(([, c]) => c.axis === axis);
    rows.forEach(([dim, c], i) => {
      w(`| ${i === 0 ? `**${axis}**` : ''} | ${label(dim)} | ${pct(c.weight)} | ${c.invert ? 'yes' : 'no'} |`);
    });
    const total = rows.reduce((a, [, c]) => a + c.weight, 0);
    w(`| | _total_ | _${pct(total)}_ | |`);
  }
  w('',
    'A dimension that is on neither axis still has a score and still has a page.',
    'It is not part of the couple type.',
    '');

  // ── 1.3 self vs blended
  w('### 1.3 Self-report and blended, and which one is used where',
    '',
    'Each person is scored twice. The **self** score is their own answers. The',
    '**blended** score mixes in their partner\'s view of them, by dimension:',
    '',
    '| Dimension | Their own answers | Their partner\'s view of them |',
    '|--|--|--|');
  for (const [dim, b] of Object.entries(PARTNER_VIEW_BLEND)) {
    w(`| ${label(dim)} | ${pct(b.self)} | ${pct(b.partner)} |`);
  }
  w('',
    'The blend is heavier toward the partner on the dimensions a person tends to',
    'be a poor witness of in themselves.',
    '',
    '**Which is used where.** The couple type is derived from the blended scores,',
    'because how you are seen is part of the dynamic. Everything a reader is shown',
    'about where they placed themselves is the self score: the marks on every',
    'slider, the gap between two people, and the alignment percentage.',
    '',
    'The reason is that mixing two numbers usually moves each toward the other, so',
    'a blended gap is narrower than the real one more often than not. Swept over',
    "every combination of two people's answers and two people's views of each",
    'other, the blended gap is narrower 58 per cent of the time and wider 28; when',
    'each of them reads the other within a point, which is the ordinary case, it is',
    'narrower 74 per cent and wider 14. So it is a tendency rather than a rule, and',
    'it was enough: a card once read 100 per cent aligned while the sliders above it',
    'visibly did not touch.',
    '');

  // ── 1.4 domains
  w('### 1.4 The three Communication pages',
    '',
    '| Page | Dimensions |',
    '|--|--|');
  for (const d of COMM_DOMAINS) {
    w(`| ${d.label} | ${(d.dims || []).map(label).join(', ')} |`);
  }
  w('');

  // ── 2. ALIGNMENT ────────────────────────────────────────────────────────
  w('## 2. How aligned two people are',
    '',
    'One module decides what a distance means, for every exercise:',
    '`api/_lib/alignment.js`. Each exercise measures its own distance, because the',
    'instruments differ, and then asks that one module how close that is and what',
    'to say about it.',
    '',
    '### 2.1 The bands',
    '',
    'Distances are normalised to 0 (identical answers) and 1 (opposite ends).',
    '',
    '| Band | Distance | What it means |',
    '|--|--|--|',
    `| Aligned | 0 to ${ALIGNMENT_BANDS.aligned} | The two answers are the same, or as near as makes no difference |`,
    `| Discuss | ${ALIGNMENT_BANDS.aligned} to ${ALIGNMENT_BANDS.discuss} | Close, and worth a conversation |`,
    `| Different | above ${ALIGNMENT_BANDS.discuss} | Far enough apart to be the subject of one |`,
    '',
    '**The percentage on any bar** is the distance inverted: identical answers read',
    '100, opposite ends read 0. A category bar is the mean of its rows. An',
    'unanswered item is left out of that mean rather than counted as zero, because',
    'a question nobody answered is not a disagreement.',
    '',
    '### 2.2 The one deliberate exception',
    '',
    'Communication does not use these bands. Its line is one point on a',
    `one-to-five scale (\`CARD_ALIGNED_GAP\` = ${CARD_ALIGNED_GAP}), which normalises to`,
    `${CARD_ALIGNED_GAP / 4} rather than the ${ALIGNMENT_BANDS.aligned} above. It has not been moved because moving it`,
    'changes the alignment figure on every storycard every existing customer has',
    'already read. That is a decision for Ellie rather than a side effect.',
    '',
    '**Whether a couple is misaligned overall** is a different question again, and',
    `uses a third threshold: a gap of ${ALIGNMENT_THRESHOLD.gap} or more on at least`,
    `${ALIGNMENT_THRESHOLD.dims} of the ten dimensions. One wide gap is not a`,
    'misaligned couple.',
    '');

  // ── 3. EXPECTATIONS ─────────────────────────────────────────────────────
  const respItems = RESPONSIBILITY_CATEGORIES.reduce((n, c) => n + c.items.length, 0);
  w('## 3. Expectations',
    '',
    `${respItems} responsibilities across ${RESPONSIBILITY_CATEGORIES.length} categories, and`,
    `${LIFE_QUESTIONS.length} life questions.`,
    '',
    '### 3.1 The mirror, which is the hard part',
    '',
    'These questions are asked in the first person. Two people who both answer',
    '"primarily mine" have **disagreed**: each has claimed the same job. Two who',
    'answer oppositely have **agreed**. So one side is flipped before the two are',
    'compared, in the key and in the value. Getting it backwards inverts every',
    'result while looking entirely reasonable.',
    '',
    '### 3.2 The five-point scale',
    '',
    'Answering "Both of us" opens a follow-up asking which way it leans, and that',
    'follow-up is part of the comparison:',
    '',
    '| Position | Answer |',
    '|--|--|',
    '| 0 | Them, by name |',
    '| 0.5 | Both of us, usually them |',
    '| 1 | Both of us, genuinely half, or Both with nothing more said |',
    '| 1.5 | Both of us, usually their partner |',
    '| 2 | Their partner, by name |',
    '',
    'The distance is the gap between the two positions over 2. So one step apart',
    'reads 75 per cent close and opposite ends read 0.',
    '',
    '"Doesn\'t apply" stays off this scale. Both saying it is agreement; one saying',
    'it against a named person is a full difference.',
    '',
    '### 3.3 Life questions',
    '',
    'Each has an ordered list of options and the distance is the index gap over',
    'the widest possible one.',
    '',
    '| Question | Options |',
    '|--|--|');
  for (const [id, opts] of Object.entries(LIFE_QUESTION_OPTIONS)) {
    w(`| \`${id}\` | ${opts.length} |`);
  }
  w('',
    '**An honest caveat.** Three or four of these are categorical rather than',
    'linear: the options are different kinds of answer rather than points on a',
    'scale, so the distance between two of them is an approximation. It is the',
    'same approximation the percentage has always used, and it is recorded here',
    'rather than left to be discovered.',
    '',
    '### 3.4 Two roll-ups, one score',
    '',
    'The per-item score has one rule. It is summarised two ways, because two',
    'different figures are drawn next to two different things:',
    '',
    `- **The category bars** average the ${EXPECTATIONS_CATEGORIES.length} categories, because a bar is labelled with a category.`,
    /* Quoted, not comma-joined. One of the five is called "Money, Work &
       Career", so a comma-separated list of five reads as a list of six: the
       figure said 5 and the sentence beside it showed six names. */
    `- **The headline percentage** averages ${EXP_DOMAINS.length} domains, which cut across the categories: ${EXP_DOMAINS.map((d) => `"${d.label}"`).join(', ')}. Each counts equally, so Household's ${RESPONSIBILITY_CATEGORIES.find((c) => c.id === 'household')?.items.length} items do not outweigh Emotional Labor's ${RESPONSIBILITY_CATEGORIES.find((c) => c.id === 'emotional')?.items.length}.`,
    '');

  // ── 4. INTIMACY ─────────────────────────────────────────────────────────
  w('## 4. Physical Intimacy',
    '',
    `${INTIMACY_QUESTIONS.length} questions across ${INTIMACY_DIMENSIONS.length} aspects. Three kinds of question, scored three ways.`,
    '',
    '| Kind | How two answers are compared |',
    '|--|--|',
    '| Scale | Each option carries a position from 0 to 1. The distance is the gap. |',
    '| Self-referential | "Mostly me" from one and "mostly my partner" from the other describe the SAME split, so one side is mirrored before comparing. Both claiming the same side is a contradiction and scores as the widest possible gap. |',
    '| Multi-select | The overlap of the two sets: one minus shared over total. |',
    '',
    'Every question has a "prefer not to say". Both declining is its own state and',
    'is never read as agreement. One declining leaves the pair uncounted rather',
    'than scored, so choosing not to answer does not become a signal of its own.',
    '',
    '| Aspect | Questions |',
    '|--|--|');
  for (const d of INTIMACY_DIMENSIONS) {
    w(`| ${d.label} | ${INTIMACY_QUESTIONS.filter((q) => q.dimension === d.id).length} |`);
  }
  w('',
    'An aspect is the mean of its questions, and lands in the bands in §2.1.',
    '');

  // ── 5. CONFLICT ─────────────────────────────────────────────────────────
  w('## 5. Conflict Patterns',
    '',
    `${Object.keys(PATTERN_COPY).length} patterns, each self-assigned on a ${FREQUENCY_LABELS.length}-point frequency scale:`,
    `${FREQUENCY_LABELS.map((f, i) => `${i} ${f}`).join(', ')}.`,
    '',
    'Nothing is scored against anybody else. This is the one section that is not',
    'a comparison: the reader rates themselves and the result is their own, and it',
    "is never sent to their partner's device. What advice a pattern gets depends",
    'only on where it falls on that scale.',
    '',
    '| Answer | What the results do with it |',
    '|--|--|',
    `| ${FREQUENCY_LABELS[0]} | Nothing to act on. Attaching an instruction to a pattern that is not happening would read as a warning about nothing. |`,
    `| ${FREQUENCY_LABELS[1]} | An awareness note. |`,
    `| ${FREQUENCY_LABELS[2]} and ${FREQUENCY_LABELS[3]} | One thing to try. |`,
    '');

  // ── 6. WHAT IS NOT RECOMPUTED ───────────────────────────────────────────
  w('## 6. Results are frozen, and what that means',
    '',
    "Once a couple's results row is written it is served back as it was written.",
    'A scoring change therefore reaches new couples only.',
    '',
    'Anything a display needs that can be derived from what is already stored is',
    'derived on the way out instead, which reaches everybody. The expectations and',
    'intimacy figures in this document are computed from the stored answers on',
    'every request, so the rules above apply to a couple who finished last year.',
    '');

  return `${L.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = build();
  if (out.length < 4000) throw new Error(`methodology came out ${out.length} bytes, which is not a document`);
  writeFileSync(OUT, out);
  console.log(`[build-methodology] METHODOLOGY.md written, ${out.length} bytes.`);
}
