#!/usr/bin/env node
/**
 * COUPLE-TYPE-COPY-REVIEW.md, generated from api/_couple-types.js.
 *
 * ── WHAT IT IS FOR ────────────────────────────────────────────────────────
 * Ellie: "I want to simplify the 4 paragraphs under what comes naturally and
 * what's worth being aware of. Can you build me a table of each of the prose
 * options for those sections and what they could be if we were to make them
 * shorter (think bullet-point rather than its own tile). I will review the
 * list and we will go from there."
 *
 * There are 60 of them rather than four: three strengths and three sticking
 * points for each of ten couple types, and a couple only ever meets their own
 * six. The table is all of them because a decision about the shape of this
 * copy is a decision about all sixty.
 *
 * ── THE CURRENT COLUMN IS READ, THE SHORTER COLUMN IS DATA ────────────────
 * The left column comes from the module the product serves, so it cannot
 * drift. The right column is a proposal and lives in
 * scripts/couple-type-short.json, which is NOT product copy and is read by
 * nothing else.
 *
 * Each proposal records the sentence it was written against. If the module's
 * sentence changes, the proposal is marked STALE in the document rather than
 * being shown beside a sentence it was never about. That is the failure this
 * repo has already paid for once: a review document that quietly describes
 * something other than what ships.
 *
 * ── WHERE HER ANSWER GOES ─────────────────────────────────────────────────
 * Into api/_couple-types.js, the moment it arrives. Not into this document:
 * the next run of this script would erase it, which is exactly how her 74
 * insights were nearly lost.
 *
 * Run: node scripts/build-couple-type-copy-review.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { COUPLE_TYPES } from '../api/_couple-types.js';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = `${ROOT}COUPLE-TYPE-COPY-REVIEW.md`;
const SHORT = JSON.parse(readFileSync(`${ROOT}scripts/couple-type-short.json`, 'utf8'));

/** Enough of the current sentence to notice it being rewritten. */
const fingerprint = (s) => String(s).replace(/\s+/g, ' ').trim().slice(0, 48);

const rows = [];
let stale = 0;
let missing = 0;
for (const type of COUPLE_TYPES) {
  const prop = SHORT[type.id] || { S: [], P: [] };
  const sets = [
    ['What comes naturally', type.strengths || [], prop.S || []],
    ["What's worth being aware of", type.stickingPoints || [], prop.P || []],
  ];
  for (const [heading, now, shorter] of sets) {
    now.forEach((sentence, i) => {
      const proposal = shorter[i];
      if (!proposal) { missing += 1; }
      /* A proposal records the sentence it was written against. If that has
         changed, the proposal is about a sentence nobody will read, so it is
         marked rather than shown as though it answered this one. */
      const drifted = !!proposal && proposal.was !== fingerprint(sentence);
      if (drifted) stale += 1;
      rows.push({
        type: type.name, id: type.id, heading, n: i + 1,
        now: sentence,
        shorter: !proposal ? '(nothing proposed)'
          : drifted ? `**STALE**, written against: "${proposal.was}..." ${proposal.short}`
            : proposal.short,
        stale: drifted,
      });
    });
  }
  /* A proposal with no sentence left to be about at all. */
  const extra = (prop.S.length - (type.strengths || []).length)
    + (prop.P.length - (type.stickingPoints || []).length);
  if (extra > 0) stale += extra;
}

const table = (heading) => rows.filter((r) => r.heading === heading).map((r) =>
  `| ${r.id} | ${r.n} | ${r.now.replace(/\|/g, '\\|')} | ${r.shorter.replace(/\|/g, '\\|')} |`).join('\n');

const chars = (list) => {
  const a = list.reduce((s, r) => s + r.now.length, 0) / list.length;
  const b = list.reduce((s, r) => s + r.shorter.length, 0) / list.length;
  return [Math.round(a), Math.round(b)];
};
const [nowAvg, shortAvg] = chars(rows);

const doc = `# Couple type copy, long and short

Generated from \`api/_couple-types.js\` by
\`scripts/build-couple-type-copy-review.mjs\`. Do not edit this file: it is
rebuilt from the product and your edits here would be erased. Tell me which
column you want, per row or in bulk, and it goes into the module.

You asked for "the 4 paragraphs under what comes naturally and what's worth
being aware of". There are **${rows.length}**: three of each for all ten couple
types. A couple only ever sees their own six, and you only ever see your own,
which is why it reads as four or six rather than sixty.

The left column is what ships today. The right column is a proposal, roughly a
bullet rather than a paragraph: **${nowAvg} characters now, ${shortAvg}
proposed**.

Nothing here is live. Nothing changes until you say so.

## The names, so the tokens read

\`{U}\` and \`{P}\` are the two people. \`{EXP}\`, \`{GRD}\`, \`{RCH}\` and
\`{WDR}\` are roles the couple's own axes decide, and the product resolves all
of them to a name before anyone reads them. Where a proposal keeps a token, it
is the same token the current sentence uses.

## What comes naturally

| Type | # | Now | Shorter |
|--|--|--|--|
${table('What comes naturally')}

## What's worth being aware of

| Type | # | Now | Shorter |
|--|--|--|--|
${table("What's worth being aware of")}

## The ten types, by id

${COUPLE_TYPES.map((t) => `- **${t.id}** ${t.name}`).join('\n')}
`;

writeFileSync(OUT, doc);
console.log(`[build-couple-type-copy-review] ${rows.length} rows written to COUPLE-TYPE-COPY-REVIEW.md`
  + ` (${nowAvg} characters now, ${shortAvg} proposed`
  + `${missing ? `, ${missing} with nothing proposed` : ''}${stale ? `, ${stale} stale` : ''}).`);
