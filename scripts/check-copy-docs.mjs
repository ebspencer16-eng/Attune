#!/usr/bin/env node
/**
 * The prose in TASKS.md has to be the prose the product sends.
 *
 * ── THE PROMISE ───────────────────────────────────────────────────────────
 * Ellie: "Please make this the practice from now on so that I can review all
 * prose in the tasks document." That only works if the document cannot drift.
 * Twice now a surface built to show the product quietly became a second draft
 * of it: /email-preview held six hand-written mock-ups while nineteen real
 * emails went out, and the copy-review document listed ten action items the
 * product never rendered. In both cases words were reviewed and approved that
 * nobody would ever read, and the words that shipped went unreviewed.
 *
 * So the blocks are generated, and this regenerates them and refuses a
 * difference. Same shape as check-notification-copy-doc.mjs, one level up.
 *
 * ── WHAT IT DELIBERATELY DOES NOT COVER ───────────────────────────────────
 * Whether the words are good, which is the whole reason the blocks exist. Nor
 * whether every piece of prose in the product has a block yet: the blocks are
 * added as she asks for them, and a missing one is a gap she can see rather
 * than a lie she cannot.
 */

import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const ROOT = new URL('..', import.meta.url).pathname;
const doc = readFileSync(`${ROOT}TASKS.md`, 'utf8');

const fresh = execFileSync('node', [`${ROOT}scripts/build-copy-docs.mjs`, '--print'], { encoding: 'utf8' });
/**
 * Split the printed output on its headings.
 *
 * The first version did this with one regex whose lookahead ended at `$` under
 * the m flag, which is the end of every line, so each block came back as its
 * own first sentence and every comparison failed. Walking the headings is
 * duller and cannot mean something else.
 */
const heads = [...fresh.matchAll(/^## ([\w-]+)$/gm)];
const blocks = heads.map((h, i) => [
  null,
  h[1],
  fresh.slice(h.index + h[0].length, i + 1 < heads.length ? heads[i + 1].index : undefined),
]);
/**
 * No blocks is a legitimate state, not a broken generator.
 *
 * Ellie reads a table, sends her changes, approves them, and asks for the
 * table to come out. When the last one goes the generator has nothing to
 * print, and a check that reads that as a failure is a check that fails every
 * run until someone silences it. Separating "nothing under review" from
 * "broken" is the same lesson as check:docs reporting eighteen failures that
 * were really eighteen sandbox paths.
 */
if (!blocks.length) {
  console.log('[check-copy-docs] no prose blocks under review.');
  process.exit(0);
}

const fails = [];
for (const [, name, content] of blocks) {
  const start = `<!-- copy:${name}: generated by scripts/build-copy-docs.mjs -->`;
  const end = `<!-- end copy:${name} -->`;
  const from = doc.indexOf(start);
  const to = doc.indexOf(end);
  if (from < 0 || to < 0) { fails.push(`the ${name} block is gone from TASKS.md`); continue; }
  const onDisk = doc.slice(from + start.length, to).trim();
  if (onDisk !== content.trim()) {
    const a = onDisk.split('\n');
    const b = content.trim().split('\n');
    const i = a.findIndex((l, n) => l !== b[n]);
    fails.push(
      `the ${name} block no longer matches the product\n`
      + `      in TASKS.md: ${a[i] ?? '(nothing)'}\n`
      + `      in the code: ${b[i] ?? '(nothing)'}`,
    );
  }
}

if (fails.length) {
  console.error('[check-copy-docs] TASKS.md describes copy the product does not send:');
  for (const f of fails) console.error(`  ${f}`);
  console.error('');
  console.error('Run: node scripts/build-copy-docs.mjs');
  process.exit(1);
}

console.log(`[check-copy-docs] ${blocks.length} prose blocks in TASKS.md, every one of them the product's own words.`);
